#!/usr/bin/env python3
"""Generate vector icon tables from SVG sources.

Supported SVG primitives: line, polyline, polygon, rect, circle.
Icons are authored on a 0..16 viewBox; output coordinates are normalized 0..1.
The renderer draws these as stroked polylines, which stays crisp at any DPI.
"""

from __future__ import annotations

import math
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
ICON_DIR = ROOT / "assets" / "icons"
RUST_OUT = ROOT / "ui" / "src" / "icons.rs"
CS_OUT = ROOT / "scripts" / "IconIds.cs"
VIEWBOX = 16.0


def parse_points(text: str) -> list[tuple[float, float]]:
    nums = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", text)]
    return [(nums[i], nums[i + 1]) for i in range(0, len(nums) - 1, 2)]


def segments_for(path: pathlib.Path) -> list[tuple[float, float, float, float]]:
    root = ET.parse(path).getroot()
    segs: list[tuple[float, float, float, float]] = []
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        if tag == "line":
            segs.append((float(el.get("x1", 0)), float(el.get("y1", 0)),
                         float(el.get("x2", 0)), float(el.get("y2", 0))))
        elif tag in ("polyline", "polygon"):
            pts = parse_points(el.get("points", ""))
            for a, b in zip(pts, pts[1:]):
                segs.append((a[0], a[1], b[0], b[1]))
            if tag == "polygon" and len(pts) > 2:
                segs.append((pts[-1][0], pts[-1][1], pts[0][0], pts[0][1]))
        elif tag == "rect":
            x = float(el.get("x", 0))
            y = float(el.get("y", 0))
            w = float(el.get("width", 0))
            h = float(el.get("height", 0))
            pts = [(x, y), (x + w, y), (x + w, y + h), (x, y + h), (x, y)]
            for a, b in zip(pts, pts[1:]):
                segs.append((a[0], a[1], b[0], b[1]))
        elif tag == "circle":
            cx = float(el.get("cx", 0))
            cy = float(el.get("cy", 0))
            r = float(el.get("r", 0))
            steps = 20
            pts = [
                (cx + r * math.cos(2 * math.pi * i / steps),
                 cy + r * math.sin(2 * math.pi * i / steps))
                for i in range(steps + 1)
            ]
            for a, b in zip(pts, pts[1:]):
                segs.append((a[0], a[1], b[0], b[1]))
    return [(a / VIEWBOX, b / VIEWBOX, c / VIEWBOX, d / VIEWBOX) for a, b, c, d in segs]


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[-_]", name))


def main() -> int:
    files = sorted(ICON_DIR.glob("*.svg"))
    if not files:
        print(f"no SVG icons under {ICON_DIR}", file=sys.stderr)
        return 1

    rust = [
        "// Generated by engine/scripts/gen_icons.py from engine/assets/icons/*.svg.",
        "// Do not edit by hand.",
        "",
        "pub struct IconDef {",
        "    pub name: &'static str,",
        "    pub segments: &'static [(f32, f32, f32, f32)],",
        "}",
        "",
        "pub const ICONS: &[IconDef] = &[",
    ]
    cs = [
        "// Generated by engine/scripts/gen_icons.py. Do not edit by hand.",
        "namespace Hezhou",
        "{",
        "    public enum IconId : uint",
        "    {",
    ]
    for index, path in enumerate(files):
        name = path.stem
        segs = segments_for(path)
        rust.append(f'    IconDef {{ name: "{name}", segments: &[')
        for a, b, c, d in segs:
            rust.append(f"        ({a:.4}, {b:.4}, {c:.4}, {d:.4}),")
        rust.append("    ] },")
        cs.append(f"        {pascal(name)} = {index},")
    rust += [
        "];",
        "",
        "pub const ICON_COUNT: u32 = ICONS.len() as u32;",
        "",
        "pub fn icon(index: u32) -> Option<&'static IconDef> {",
        "    ICONS.get(index as usize)",
        "}",
        "",
    ]
    cs += ["    }", "}", ""]
    RUST_OUT.write_text("\n".join(rust), encoding="utf-8", newline="\n")
    CS_OUT.write_text("\n".join(cs), encoding="utf-8", newline="\n")
    print(f"generated {len(files)} icons -> {RUST_OUT.name}, {CS_OUT.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
